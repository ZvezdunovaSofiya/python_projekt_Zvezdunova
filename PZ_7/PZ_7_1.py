# Дана непустая строка S и целое число N (>0).
# Вывести строку, содержащую символы строки S, 
# между которыми вставлено по N символов «*».

S = input('Введите непустую строку S: ')
N = int(input('Введите целое число N (>0): '))

# Формируем строку из N звездочек
stars = '*' * N

# В переменной result будет собираться итоговая строка
result = ''

# Проходим по всем символам строки S по индексам
for i in range(len(S)):
    # Добавляем текущий символ
    result = result + S[i]
    
    # Если это не последний символ строки, добавляем звездочки
    if i < len(S) - 1:
        result = result + stars

print('Исходная строка: ', S)
print('Результирующая строка: ', result)