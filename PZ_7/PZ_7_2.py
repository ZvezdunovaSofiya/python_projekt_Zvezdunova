# Дана строка-предложение на русском языке. 
# Вывести самое короткое слово в предложении. 
# Если таких слов несколько, то вывести последнее из них.

import string

text = input('Введите предложение на русском языке: ')

# Заменяем все знаки препинания на пробелы, чтобы они не прилипали к словам
for char in string.punctuation:
    text = text.replace(char, ' ')

# Разбиваем строку на список слов по пробелам
words = text.split()

# Инициализируем переменные для хранения самого короткого слова и его длины
# Берем за начальное значение первое слово
shortest_word = words[0]
min_len = len(words[0])

# Проходим по всем словам в списке
for word in words:
    # Если длина текущего слова меньше минимальной
    # или равна минимальной (чтобы взять ПОСЛЕДНЕЕ из них)
    if len(word) <= min_len:
        min_len = len(word)
        shortest_word = word

print('Самое короткое слово (последнее из них): ', shortest_word)
