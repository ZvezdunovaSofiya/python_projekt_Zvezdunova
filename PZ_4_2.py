# Дано целое число N (> 1). Вывести наибольшее из целых чисел K, 
# для которых сумма 1 + 2 + ... + K будет меньше или равна N, и саму эту сумму.

n = input("Введите число N: ")

# Обработка исключений (как в методичке)
while type(n) != int:
    try:
        n = int(n)
        if n <= 1:
            print("Число должно быть больше 1!")
            n = input("Введите число N: ")
    except ValueError:
        print("Неправильно ввели!")
        n = input("Введите число N: ")

k = 0 # Наше число K (сначала 0)
s = 0 # Наша сумма (сначала 0)

# Крутим цикл, пока сумма не превысит N
while s <= n:
    k += 1 # Увеличиваем K на 1 (будет 1, 2, 3...)
    s += k # Прибавляем это K к сумме

# ВНИМАНИЕ: Цикл остановился, когда s стало БОЛЬШЕ n. 
# Значит, последнее число k мы прибавили зря. 
# Делаем шаг назад, чтобы сумма снова стала "меньше или равна N":
k -= 1
s -= (k + 1) # Отнимаем то самое "лишнее" последнее число

print("Наибольшее число K:", k)
print("Сумма:", s)