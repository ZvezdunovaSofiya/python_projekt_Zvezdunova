# Дано целое число N (>0). Найти значение выражения 1.1 - 1.2 + 1.3 - ... (N слагаемых, знаки чередуются). Условный оператор не использовать.

n = input("Введите число N: ")

# Стандартная обработка исключений 
while type(n) != int:
    try:
        n = int(n)
        if n <= 0:
            print("Число должно быть больше 0!")
            n = input("Введите число N: ")
    except ValueError:
        print("Неправильно ввели!")
        n = input("Введите число N: ")

s = 0.0 # Здесь будем накапливать итоговую сумму
sign = 1 # Переменная для чередования знаков 
i = 1 # Счетчик шагов (от 1 до N)

while i <= n:
    # Формируем само число: 1.1, 1.2, 1.3 и т.д.
    # Для этого к 1 прибавляем i, деленное на 10.0
    term = 1.0 + (i / 10.0)
    # Прибавляем к общей сумме слагаемое, умноженное на текущий знак
    s += sign * term

    # Меняем знак на противоположный (если был 1, станет -1; если был -1, станет 1)
    sign = -sign 
    i += 1
print("Значение выражения:", s)